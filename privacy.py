
# ~ ----------------------------------------------
# ~ Política de privacidad — Proyecto académico
# ~ ----------------------------------------------

# Esta aplicación es el MVP de un proyecto académico y la versión publicada
# en el track de prueba utiliza exclusivamente datos sintéticos
# generados para demostraciones.
# 
# No se recolectan, procesan ni comparten datos personales de personas reales
# en este entorno de demostración.
# 
# Las contraseñas en la base de datos están almacenadas únicamente
# de forma hasheada.
# 
# Cualquier envío a servicios externos
# están desactivados en el entorno de demo.
# 
# Si la app comienza a procesar datos reales en el futuro,
# se informará a los usuarios y se solicitará su consentimiento explícito.

